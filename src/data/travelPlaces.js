// ---------- Search ----------

function normalize(value) {
  return value.toLowerCase().trim();
}

/** True if any whole word in `text` starts with `q` — used for the
 * secondary (type/region/state/keyword) tier so a query like "tri"
 * can match a real word like "tribal" but not an unrelated substring
 * buried mid-word (e.g. "ma-tri-mandir"). */
function wordStartMatches(text, q) {
  return normalize(text)
    .split(/[^a-z0-9]+/)
    .some((word) => word && word.startsWith(q));
}

/** Highest-scoring match wins; 100 = exact name, down to 40 for a
 * looser keyword/region/type/state match. Returns -1 for no match. */
function scorePlace(place, q) {
  let best = -1;

  const consider = (text, exact, starts, includes) => {
    if (!text) return;
    const t = normalize(text);
    if (t === q) best = Math.max(best, exact);
    else if (t.startsWith(q)) best = Math.max(best, starts);
    else if (t.includes(q)) best = Math.max(best, includes);
  };

  consider(place.name, 100, 90, 70);
  place.aliases.forEach((alias) => consider(alias, 96, 86, 66));

  const metaBlob = [place.type, place.region, place.state, ...place.searchKeywords].join(' ');
  if (wordStartMatches(metaBlob, q)) best = Math.max(best, 40);

  return best;
}

/**
 * Searches the full destination dataset (case-insensitive, partial,
 * alias- and keyword-aware) and returns every match, strongest first.
 * The caller decides how many of these to actually render.
 *
 * @param {string} query
 * @param {Object} [options]
 * @param {string[]} [options.excludeSlugs] - places to leave out entirely
 *   (e.g. the hero's "Going to" field excluding "kanyakumari", the
 *   trip's own starting point — going there wouldn't make sense)
 * @returns {TravelPlace[]}
 */
export function searchTravelPlaces(query, { excludeSlugs = [] } = {}) {
  const q = normalize(query || '');
  if (!q) return [];

  return travelPlaces
    .filter((place) => !excludeSlugs.includes(place.slug))
    .map((place) => ({ place, score: scorePlace(place, q) }))
    .filter((entry) => entry.score > -1)
    .sort((a, b) => b.score - a.score || a.place.name.localeCompare(b.place.name))
    .map((entry) => entry.place);
}
