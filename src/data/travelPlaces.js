/**
 * Centralized destination SEARCH index — every real place a Shivdev
 * Holidays customer could plausibly search for and travel to by cab,
 * with Tamil Nadu as the deepest layer and strong Kerala coverage,
 * plus the nearby Karnataka / Andhra Pradesh / Telangana / Puducherry
 * hubs and airports travellers connect through.
 *
 * This is deliberately a SEPARATE, lighter-weight shape from
 * data/destinations.js (which holds the small set of fully built
 * destination pages). The six places that already have a real page
 * are NOT re-typed here — see `destinationEntries` below, which
 * projects data/destinations.js into this same search shape at
 * module load, so that file stays the single source of truth for
 * its own content (name/slug/region/shortDescription/placesToSee).
 * Everything else here is a place that doesn't have a dedicated page
 * yet; the same `slug` shape (/destinations/:slug) is used for all of
 * them so a page can be added later without touching the search code.
 *
 * @typedef {Object} TravelPlace
 * @property {string} name - canonical display name
 * @property {string} slug - URL segment, used at /destinations/:slug
 * @property {string} state
 * @property {string} region - broad area within the state
 * @property {string} type - see TYPE_LABELS below
 * @property {string[]} aliases - alternate real names/spellings/abbreviations
 * @property {string} shortDescription - one plain sentence
 * @property {string[]} popularPlaces - a few well-known spots there
 * @property {string[]} searchKeywords - extra real search terms (themes, etc.)
 * @property {boolean} hasPage - whether /destinations/:slug is a real, built page
 */

